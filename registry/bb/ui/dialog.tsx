"use client"

import * as React from "react"
import { cva } from "class-variance-authority"
import { XIcon } from "lucide-react"
import { Dialog as DialogPrimitive } from "radix-ui"

import { Button } from "@/components/ui/button"
import { cn } from "@/lib/utils"

type DialogLayout = "default" | "steps"

const DialogContentContext = React.createContext<{
  layout: DialogLayout
  showCloseButton: boolean
}>({ layout: "default", showCloseButton: false })

function Dialog({
  ...props
}: React.ComponentProps<typeof DialogPrimitive.Root>) {
  return <DialogPrimitive.Root data-slot="dialog" {...props} />
}

function DialogTrigger({
  ...props
}: React.ComponentProps<typeof DialogPrimitive.Trigger>) {
  return <DialogPrimitive.Trigger data-slot="dialog-trigger" {...props} />
}

function DialogPortal({
  ...props
}: React.ComponentProps<typeof DialogPrimitive.Portal>) {
  return <DialogPrimitive.Portal data-slot="dialog-portal" {...props} />
}

function DialogClose({
  ...props
}: React.ComponentProps<typeof DialogPrimitive.Close>) {
  return <DialogPrimitive.Close data-slot="dialog-close" {...props} />
}

function DialogOverlay({
  className,
  ...props
}: React.ComponentProps<typeof DialogPrimitive.Overlay>) {
  return (
    <DialogPrimitive.Overlay
      data-slot="dialog-overlay"
      className={cn("fixed inset-0 z-50 bg-primary/40", className)}
      {...props}
    />
  )
}

const dialogContentVariants = cva(
  "fixed top-1/2 left-1/2 z-50 max-h-[calc(100dvh-2rem)] w-[calc(100%-2rem)] -translate-1/2 rounded-xl border border-border bg-card text-left text-foreground shadow-panel focus:outline-none",
  {
    variants: {
      size: {
        md: "max-w-md",
        lg: "max-w-lg",
        xl: "max-w-2xl",
      },
      layout: {
        default: "grid gap-5 overflow-y-auto p-6",
        steps: "flex h-88 flex-col gap-0 overflow-hidden p-0",
      },
    },
    defaultVariants: {
      size: "lg",
      layout: "default",
    },
  }
)

function DialogContent({
  className,
  children,
  size = "lg",
  layout = "default",
  showCloseButton = true,
  closeLabel = "Venster sluiten",
  closeOnOutsideClick = false,
  onInteractOutside,
  ...props
}: React.ComponentProps<typeof DialogPrimitive.Content> & {
  size?: "md" | "lg" | "xl"
  layout?: DialogLayout
  showCloseButton?: boolean
  closeLabel?: string
  closeOnOutsideClick?: boolean
}) {
  const context = React.useMemo(
    () => ({ layout, showCloseButton }),
    [layout, showCloseButton]
  )

  return (
    <DialogPortal>
      <DialogOverlay />
      <DialogPrimitive.Content
        data-slot="dialog-content"
        data-size={size}
        data-layout={layout}
        className={cn(dialogContentVariants({ size, layout }), className)}
        onInteractOutside={(event) => {
          onInteractOutside?.(event)
          if (!closeOnOutsideClick) event.preventDefault()
        }}
        {...props}
      >
        <DialogContentContext.Provider value={context}>
          {children}
        </DialogContentContext.Provider>
        {showCloseButton && (
          <DialogPrimitive.Close asChild>
            <Button
              data-slot="dialog-close"
              variant="ghost"
              size="icon-sm"
              aria-label={closeLabel}
              className="absolute top-6 right-6"
            >
              <XIcon aria-hidden="true" />
            </Button>
          </DialogPrimitive.Close>
        )}
      </DialogPrimitive.Content>
    </DialogPortal>
  )
}

function DialogHeader({ className, ...props }: React.ComponentProps<"div">) {
  const { layout, showCloseButton } = React.useContext(DialogContentContext)

  return (
    <div
      data-slot="dialog-header"
      className={cn(
        "flex min-w-0 flex-col gap-2",
        layout === "steps" && "gap-1 px-6 pt-6 pb-4",
        showCloseButton &&
          (layout === "steps" ? "min-h-18 pr-18" : "min-h-8 pr-12"),
        className
      )}
      {...props}
    />
  )
}

function DialogStep({ className, ...props }: React.ComponentProps<"p">) {
  return (
    <p
      data-slot="dialog-step"
      className={cn("text-xs font-semibold text-muted-foreground", className)}
      {...props}
    />
  )
}

/**
 * In `steps` the scrolling middle: focusable, and a region labelled by the
 * dialog title unless `aria-label` or `aria-labelledby` is given.
 */
function DialogBody({ className, id, ...props }: React.ComponentProps<"div">) {
  const { layout } = React.useContext(DialogContentContext)
  const scrolls = layout === "steps"
  const generatedId = React.useId()
  const bodyId = id ?? generatedId
  const needsLabel =
    scrolls && !props["aria-label"] && !props["aria-labelledby"]

  // The title id is generated by Radix; point at it once both are mounted.
  React.useLayoutEffect(() => {
    if (!needsLabel) return
    const body = document.getElementById(bodyId)
    const titleId = body
      ?.closest("[data-slot=dialog-content]")
      ?.querySelector("[data-slot=dialog-title]")?.id
    if (!body || !titleId) return
    body.setAttribute("aria-labelledby", titleId)
    return () => {
      if (body.getAttribute("aria-labelledby") === titleId) {
        body.removeAttribute("aria-labelledby")
      }
    }
  }, [bodyId, needsLabel])

  return (
    <div
      data-slot="dialog-body"
      id={bodyId}
      tabIndex={scrolls ? 0 : undefined}
      role={scrolls ? "region" : undefined}
      className={cn(
        scrolls
          ? "min-h-0 flex-1 overflow-y-auto px-6 pb-4 focus-visible:outline-2 focus-visible:-outline-offset-2 focus-visible:outline-ring"
          : "grid gap-5",
        className
      )}
      {...props}
    />
  )
}

function DialogFooter({ className, ...props }: React.ComponentProps<"div">) {
  const { layout } = React.useContext(DialogContentContext)

  return (
    <div
      data-slot="dialog-footer"
      className={cn(
        layout === "steps"
          ? "flex flex-wrap items-center justify-between gap-2 border-t border-border bg-card px-6 py-4"
          : "flex flex-col-reverse gap-2 sm:flex-row sm:flex-wrap sm:items-center sm:justify-end",
        className
      )}
      {...props}
    />
  )
}

/** Visual only: put the shortcut on the button as `aria-keyshortcuts`. */
function DialogHint({ className, ...props }: React.ComponentProps<"p">) {
  return (
    <p
      data-slot="dialog-hint"
      aria-hidden="true"
      className={cn(
        "mr-auto hidden text-xs text-muted-foreground sm:block",
        className
      )}
      {...props}
    />
  )
}

function DialogError({ className, ...props }: React.ComponentProps<"p">) {
  return (
    <p
      data-slot="dialog-error"
      role="alert"
      className={cn("text-sm text-destructive", className)}
      {...props}
    />
  )
}

function DialogTitle({
  className,
  ...props
}: React.ComponentProps<typeof DialogPrimitive.Title>) {
  return (
    <DialogPrimitive.Title
      data-slot="dialog-title"
      className={cn("text-lg/snug", className)}
      {...props}
    />
  )
}

function DialogDescription({
  className,
  ...props
}: React.ComponentProps<typeof DialogPrimitive.Description>) {
  return (
    <DialogPrimitive.Description
      data-slot="dialog-description"
      className={cn("text-sm text-muted-foreground", className)}
      {...props}
    />
  )
}

export {
  Dialog,
  DialogBody,
  DialogClose,
  DialogContent,
  DialogDescription,
  DialogError,
  DialogFooter,
  DialogHeader,
  DialogHint,
  DialogOverlay,
  DialogPortal,
  DialogStep,
  DialogTitle,
  DialogTrigger,
}
